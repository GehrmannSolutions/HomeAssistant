"""Generate docs/TOOLS.md from the tools the server actually registers.

Run from the ha-safe-mcp directory:  python scripts/gen_tool_reference.py
CI-friendly check (exit 1 if the file is stale):  python scripts/gen_tool_reference.py --check
"""

import asyncio
import sys
from pathlib import Path

from ha_safe_mcp.ollama_client import write_level
from ha_safe_mcp.server import HAClient, create_server

OUT = Path(__file__).resolve().parents[1] / "docs" / "TOOLS.md"

LEVELS = {
    None: ("read", "none"),
    "control": ("control", "`HA_ALLOW_WRITE`"),
    "admin": ("admin", "`HA_ALLOW_WRITE` + `HA_ALLOW_ADMIN_WRITE`"),
    "delete": ("delete", "`HA_ALLOW_WRITE` + `HA_ALLOW_ADMIN_WRITE` + `HA_ALLOW_DELETE`"),
}
# Tools whose level depends on the REST route, not on the tool name.
ROUTE_DEPENDENT = {"ha_rest_write": ("control/admin", "per route, see `ha_rest_catalog`")}

GROUPS = [
    ("States and actions", ("ha_search_entities", "ha_get_state", "ha_list_services", "ha_call_service")),
    ("Documented REST API", ("ha_rest_",)),
    ("Automations", ("_automation",)),
    ("Dashboards", ("_dashboard",)),
    ("Helpers", ("_helper",)),
    ("Entity registry", ("_entity_registry",)),
    ("Areas, floors, devices", ("_area", "_floor", "_device")),
    ("Scenes and scripts", ("_scene", "_script")),
    ("Backups", ("_backup",)),
    ("Integrations and credentials", ("_integration", "_discovered", "_credentials")),
]


def group_of(name: str) -> str:
    for title, keys in GROUPS:
        if name in keys or any(k in name for k in keys if k.startswith("_") or k.endswith("_")):
            return title
    return "Other"


def params(schema: dict) -> str:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    parts = []
    for key, spec in props.items():
        kind = spec.get("type") or "/".join(x.get("type", "?") for x in spec.get("anyOf", [])) or "object"
        parts.append(f"`{key}`" + ("" if key in required else "?") + f": {kind}")
    return ", ".join(parts) or "none"


def render() -> str:
    server = create_server(HAClient("http://127.0.0.1:8123", "x" * 32))
    tools = asyncio.run(server.list_tools())
    by_group: dict[str, list] = {}
    for tool in tools:
        by_group.setdefault(group_of(tool.name), []).append(tool)
    lines = [
        "# Tool reference",
        "",
        "<!-- Generated by scripts/gen_tool_reference.py from the registered MCP tools. Do not edit by hand. -->",
        "",
        f"`ha-safe-mcp` registers **{len(tools)} tools**. All of them are always listed; the permission check runs",
        "when a tool is called. *Level* is the permission class, *Switches* the server settings it needs in addition",
        "to a Home Assistant token whose user is allowed to do the same thing in Home Assistant. `?` marks an",
        "optional parameter. Full JSON schemas: call `tools/list` on the server.",
        "",
    ]
    order = [title for title, _ in GROUPS] + ["Other"]
    for title in order:
        if title not in by_group:
            continue
        lines += [f"## {title}", "", "| Tool | Level | Switches | Parameters | Description |", "|---|---|---|---|---|"]
        for tool in by_group[title]:
            level, switches = ROUTE_DEPENDENT.get(tool.name) or LEVELS[write_level(tool.name)]
            desc = " ".join((tool.description or "").split()).replace("|", "\\|")
            lines.append(f"| `{tool.name}` | {level} | {switches} | {params(tool.inputSchema)} | {desc} |")
        lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run scripts/gen_tool_reference.py")
            sys.exit(1)
        print("tool reference up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
